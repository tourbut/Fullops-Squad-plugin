#!/usr/bin/env python3
"""표준 원본에서 기존 CLI용 패키지를 생성한다. 생성물만 교체한다."""
import json
from pathlib import Path
import re
import shutil
import tempfile

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "plugins/fullops-squad"
NATIVE = ROOT / "dist/native/fullops-squad"
DIRECTORY = ROOT / "dist/directory/fullops-squad"
STAMP = ".fullops-generated"
# 자체 마켓플레이스판 hook 명령: 고정 런타임을 python3 -c로 실행한다. 디렉터리판은 이를 플러그인 내부 래퍼로 바꾼다.
NATIVE_HOOK = re.compile(r'python3 -c "[^"]*\.fullops-squad/runtime/fullops-squad/scripts/hook_runtime\.py[^"]*" (\w+(?: [\w-]+)*)')


def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")


def build(output=NATIVE):
    output = Path(output)
    if output.is_symlink() or (output.exists() and not (output / STAMP).is_file()):
        raise ValueError(f"빌드 생성물이 아닌 경로는 교체하지 않습니다: {output}")
    for path in SOURCE.rglob("*"):
        if path.is_symlink():
            raise ValueError(f"패키지 원본에 심볼릭 링크를 사용하지 마세요: {path}")
    manifest = json.loads((SOURCE / "plugin.json").read_text())
    mcp = json.loads((SOURCE / "mcp.json").read_text())
    native_mcp = {"mcpServers": {}}
    for name, server in mcp["mcpServers"].items():
        if server.get("type") != "stdio" or set(server) - {"type", "command", "args"}:
            raise ValueError(f"명시적인 호스트 변환이 필요한 MCP 설정: {name}")
        native_mcp["mcpServers"][name] = {k: v for k, v in server.items() if k != "type"}
    common = {key: manifest[key] for key in ("name", "version", "description", "author", "repository")}
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".fullops-build-", dir=output.parent) as temp:
        staged = Path(temp) / "fullops-squad"
        shutil.copytree(SOURCE, staged, ignore=shutil.ignore_patterns("__pycache__", "*.pyc", ".git"))
        (staged / "mcp.json").unlink()
        shutil.copy2(ROOT / "dependencies.json", staged / "dependencies.json")  # 설치된 플러그인의 deps.py가 읽는다
        shutil.copy2(ROOT / "README.md", staged / "INSTALL.md")
        shutil.copy2(ROOT / "LICENSE", staged / "LICENSE")
        shutil.copytree(ROOT / "docs/releases", staged / "releases")
        shutil.copy2(ROOT / "docs/issue-auto-mode.md", staged / "issue-auto-mode.md")
        shutil.copy2(ROOT / "docs/credentials.md", staged / "CREDENTIALS.md")
        write_json(staged / "plugin.json", {key: common[key] for key in ("name", "version", "description")})
        for host, directory in (("codex", ".codex-plugin"), ("claude-code", ".claude-plugin")):
            adapter = json.loads((ROOT / f"adapters/{host}.json").read_text())
            if set(adapter) & set(common):
                raise ValueError(f"공통 메타데이터를 adapter에서 덮어쓸 수 없습니다: {host}")
            write_json(staged / directory / "plugin.json", {**common, **adapter})
        write_json(staged / ".mcp.json", native_mcp)
        write_json(staged / "mcp_config.json", native_mcp)
        (staged / STAMP).write_text("Generated by scripts/build.py; edit plugins/fullops-squad instead.\n", newline="\n")
        replace(output, staged, Path(temp) / 'previous')
    return output


def replace(output, staged, previous):
    if output.exists():
        output.rename(previous)
    try:
        staged.rename(output)
    except Exception:
        if previous.exists():
            previous.rename(output)
        raise


def build_directory(native=NATIVE, output=DIRECTORY):
    """Anthropic 디렉터리판: 플러그인 폴더 안의 파일과 원격 https MCP만 쓰고 다른 마켓플레이스·전역 명령에 의존하지 않는다."""
    native, output = Path(native), Path(output)
    if output.is_symlink() or (output.exists() and not (output / STAMP).is_file()):
        raise ValueError(f"빌드 생성물이 아닌 경로는 교체하지 않습니다: {output}")
    adapter_root = ROOT / "adapters/claude-directory"
    common = json.loads((native / ".claude-plugin/plugin.json").read_text(encoding="utf-8"))
    adapter = json.loads((ROOT / "adapters/claude-directory.json").read_text(encoding="utf-8"))
    if {"hooks", "mcpServers", "dependencies"} & set(adapter):
        raise ValueError("디렉터리판은 기본 hooks/hooks.json만 쓰고 MCP·의존 플러그인을 선언하지 않습니다")
    manifest = {**{key: common[key] for key in ("name", "version", "repository")}, **adapter}
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".fullops-build-", dir=output.parent) as temp:
        staged = Path(temp) / "fullops-squad"
        shutil.copytree(native, staged)
        shutil.rmtree(staged / ".codex-plugin")
        (staged / "mcp_config.json").unlink()
        hooks = json.loads((staged / "hooks/hooks.json").read_text(encoding="utf-8"))
        for groups in hooks["hooks"].values():
            for group in groups:
                for hook in group["hooks"]:
                    match = NATIVE_HOOK.fullmatch(hook["command"])
                    if not match:
                        raise ValueError(f"디렉터리판으로 바꿀 수 없는 hook 명령: {hook['command']}")
                    hook["command"] = 'sh "${CLAUDE_PLUGIN_ROOT}/hooks/run.sh" ' + match[1]  # 실행 권한 비트가 없어도 동작한다
        write_json(staged / "hooks/hooks.json", hooks)
        shutil.copy2(adapter_root / "hooks/run.sh", staged / "hooks/run.sh")
        (staged / "hooks/run.sh").chmod(0o755)
        shutil.copy2(adapter_root / "README.md", staged / "README.md")
        # Context7은 전역 설치 명령 대신 원격 https 엔드포인트를 쓴다. 선택 키는 userConfig로 받는다.
        shutil.copy2(adapter_root / ".mcp.json", staged / ".mcp.json")
        write_json(staged / ".claude-plugin/plugin.json", manifest)
        replace(output, staged, Path(temp) / "previous")
    return output


def update_catalogs():
    # 마켓플레이스 등록 경로는 유지하고 배포물의 source만 갱신한다.
    for relative in (".agents/plugins/marketplace.json", ".claude-plugin/marketplace.json"):
        path = ROOT / relative
        catalog = json.loads(path.read_text())
        for entry in catalog["plugins"]:
            if entry["name"] == "fullops-squad":
                source = "./dist/native/fullops-squad"
                entry["source"] = {"source": "local", "path": source} if relative.startswith(".agents/") else source
        write_json(path, catalog)


if __name__ == "__main__":
    print(build())
    print(build_directory())
    update_catalogs()
